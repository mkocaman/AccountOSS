    private readonly ILogger<JournalEntryService> _logger;

    public JournalEntryService(
        IApplicationDbContext context,
        ICurrentUserService currentUser,
        IDocumentNumberingService numberingService,
        ILogger<JournalEntryService> logger)
    {
        _context = context;
        _currentUser = currentUser;
        _numberingService = numberingService;
        _logger = logger;
    }

    public async Task CreateInvoiceJournalEntryAsync(
        Guid invoiceId,
        CancellationToken cancellationToken = default)
    {
        try
        {
            var invoice = await _context.Invoices
                .Include(i => i.Items)
                .Where(i => i.Id == invoiceId)
                .FirstOrDefaultAsync(cancellationToken);

            if (invoice == null)
            {
                _logger.LogWarning("Invoice {InvoiceId} not found", invoiceId);
                return;
            }

            // Get accounts
            var receivableAccount = await GetSystemAccountAsync("120", cancellationToken); // Alıcılar
            var revenueAccount = await GetSystemAccountAsync("600", cancellationToken); // Satış Gelirleri
            var vatPayableAccount = await GetSystemAccountAsync("391", cancellationToken); // Hesaplanan KDV

            if (receivableAccount == null || revenueAccount == null || vatPayableAccount == null)
            {
                _logger.LogError("System accounts not found for invoice journal entry");
                return;
            }

            // Create journal entry
            var entryNumber = await _numberingService.GenerateNumberAsync("JE", cancellationToken: cancellationToken);
            var period = invoice.InvoiceDate.ToString("yyyy-MM");

            var journalEntry = new JournalEntry
            {
                Id = Guid.NewGuid(),
                CompanyId = invoice.CompanyId,
                EntryNumber = entryNumber,
                EntryDate = invoice.InvoiceDate,
                EntryType = JournalEntryType.Standard,
                ReferenceType = "Invoice",
                ReferenceId = invoice.Id,
                ReferenceNumber = invoice.InvoiceNumber,
                Description = $"Fatura: {invoice.InvoiceNumber}",
                Currency = invoice.Currency,
                TotalDebit = invoice.GrandTotal,
                TotalCredit = invoice.GrandTotal,
                Status = JournalEntryStatus.Posted,
                IsAutoGenerated = true,
                Period = period,
                CreatedAt = DateTime.UtcNow,
                CreatedBy = _currentUser.UserId ?? Guid.Empty
            };

            // Line 1: Debit - Accounts Receivable (Grand Total)
            journalEntry.Lines.Add(new JournalEntryLine
            {
                Id = Guid.NewGuid(),
                JournalEntryId = journalEntry.Id,
                AccountId = receivableAccount.Id,
                LineNumber = 1,
                Description = $"Alacak - Fatura {invoice.InvoiceNumber}",
                DebitAmount = invoice.GrandTotal,
                CreditAmount = 0,
                Currency = invoice.Currency,
                CreatedAt = DateTime.UtcNow,
                CreatedBy = _currentUser.UserId ?? Guid.Empty
            });

            // Line 2: Credit - Revenue (Subtotal)
            journalEntry.Lines.Add(new JournalEntryLine
            {
                Id = Guid.NewGuid(),
                JournalEntryId = journalEntry.Id,
                AccountId = revenueAccount.Id,
                LineNumber = 2,
                Description = "Satış Geliri",
                DebitAmount = 0,
                CreditAmount = invoice.SubTotal,
                Currency = invoice.Currency,
                CreatedAt = DateTime.UtcNow,
                CreatedBy = _currentUser.UserId ?? Guid.Empty
            });

            // Line 3: Credit - VAT Payable
            if (invoice.VatTotal > 0)
            {
                journalEntry.Lines.Add(new JournalEntryLine
                {
                    Id = Guid.NewGuid(),
                    JournalEntryId = journalEntry.Id,
                    AccountId = vatPayableAccount.Id,
                    LineNumber = 3,
                    Description = "Hesaplanan KDV",
                    DebitAmount = 0,
                    CreditAmount = invoice.VatTotal,
                    Currency = invoice.Currency,
                    CreatedAt = DateTime.UtcNow,
                    CreatedBy = _currentUser.UserId ?? Guid.Empty
                });
            }

            _context.JournalEntries.Add(journalEntry);
            await _context.SaveChangesAsync(cancellationToken);

            _logger.LogInformation("Journal entry {EntryNumber} created for invoice {InvoiceNumber}", 
                entryNumber, invoice.InvoiceNumber);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Error creating journal entry for invoice {InvoiceId}", invoiceId);
        }
    }

