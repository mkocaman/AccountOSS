    public async Task<Guid> CreateManualJournalEntryAsync(
        DateTime entryDate,
        string description,
        List<(Guid AccountId, decimal Debit, decimal Credit, string? Description)> lines,
        CancellationToken cancellationToken = default)
    {
        if (_currentUser.CompanyId == null || _currentUser.UserId == null)
            throw new InvalidOperationException("User context not available");

        // Validate: Total Debit must equal Total Credit
        var totalDebit = lines.Sum(l => l.Debit);
        var totalCredit = lines.Sum(l => l.Credit);

        if (totalDebit != totalCredit)
            throw new InvalidOperationException($"Total debit ({totalDebit}) must equal total credit ({totalCredit})");

        var entryNumber = await _numberingService.GenerateNumberAsync("JE", cancellationToken: cancellationToken);
        var period = entryDate.ToString("yyyy-MM");

        var journalEntry = new JournalEntry
        {
            Id = Guid.NewGuid(),
            CompanyId = _currentUser.CompanyId.Value,
            EntryNumber = entryNumber,
            EntryDate = entryDate,
            EntryType = JournalEntryType.Standard,
            Description = description,
            Currency = "TRY",
            TotalDebit = totalDebit,
            TotalCredit = totalCredit,
            Status = JournalEntryStatus.Draft,
            IsAutoGenerated = false,
            Period = period,
            CreatedAt = DateTime.UtcNow,
            CreatedBy = _currentUser.UserId.Value
        };

        int lineNumber = 1;
        foreach (var line in lines)
        {
            journalEntry.Lines.Add(new JournalEntryLine
            {
                Id = Guid.NewGuid(),
                JournalEntryId = journalEntry.Id,
                AccountId = line.AccountId,
                LineNumber = lineNumber++,
                Description = line.Description,
                DebitAmount = line.Debit,
                CreditAmount = line.Credit,
                Currency = "TRY",
                CreatedAt = DateTime.UtcNow,
                CreatedBy = _currentUser.UserId.Value
            });
        }

        _context.JournalEntries.Add(journalEntry);
        await _context.SaveChangesAsync(cancellationToken);

        return journalEntry.Id;
    }

    public async Task ApproveJournalEntryAsync(
        Guid journalEntryId,
        CancellationToken cancellationToken = default)
    {
        if (_currentUser.UserId == null)
            throw new InvalidOperationException("User context not available");

        var journalEntry = await _context.JournalEntries
            .Where(j => j.Id == journalEntryId)
            .FirstOrDefaultAsync(cancellationToken);

        if (journalEntry == null)
            throw new InvalidOperationException("Journal entry not found");

        if (journalEntry.Status != JournalEntryStatus.Draft && journalEntry.Status != JournalEntryStatus.PendingApproval)
            throw new InvalidOperationException("Journal entry cannot be approved in current status");

        journalEntry.Status = JournalEntryStatus.Approved;
        journalEntry.ApprovedBy = _currentUser.UserId.Value;
        journalEntry.ApprovedAt = DateTime.UtcNow;
        journalEntry.UpdatedAt = DateTime.UtcNow;
        journalEntry.UpdatedBy = _currentUser.UserId.Value;

        await _context.SaveChangesAsync(cancellationToken);
    }

    public async Task PostJournalEntryAsync(
        Guid journalEntryId,
        CancellationToken cancellationToken = default)
    {
        if (_currentUser.UserId == null)
            throw new InvalidOperationException("User context not available");

        var journalEntry = await _context.JournalEntries
            .Where(j => j.Id == journalEntryId)
            .FirstOrDefaultAsync(cancellationToken);

        if (journalEntry == null)
            throw new InvalidOperationException("Journal entry not found");

        if (journalEntry.Status != JournalEntryStatus.Approved)
            throw new InvalidOperationException("Journal entry must be approved before posting");

        journalEntry.Status = JournalEntryStatus.Posted;
        journalEntry.UpdatedAt = DateTime.UtcNow;
        journalEntry.UpdatedBy = _currentUser.UserId.Value;

        await _context.SaveChangesAsync(cancellationToken);
    }

    // Helper Methods

    private async Task<ChartOfAccount?> GetSystemAccountAsync(
        string accountCode,
        CancellationToken cancellationToken)
    {
        if (_currentUser.CompanyId == null)
            return null;

        return await _context.ChartOfAccounts
            .Where(a => a.CompanyId == _currentUser.CompanyId.Value
                     && a.AccountCode == accountCode
                     && a.IsActive)
            .FirstOrDefaultAsync(cancellationToken);
    }
}

